// Encrypts the generated question-paper bundle into api/_lib/data.js.
//
//   DATA_KEY=... node scripts/encrypt-data.mjs
//
// Reads every JSON file in public/data/ (produced by scripts/build-data.mjs),
// packs them into one object, and writes an AES-256-GCM ciphertext to
// api/_lib/data.js. The plaintext is never committed; only the server — which
// holds DATA_KEY as a secret env var — can decrypt it.

import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA_DIR = path.join(ROOT, 'public', 'data')
const OUT = path.join(ROOT, 'api', '_lib', 'data.js')

const KEY = process.env.DATA_KEY
if (!KEY) {
  console.error('[encrypt] DATA_KEY is not set.')
  console.error('[encrypt] Example:  $env:DATA_KEY="a-long-random-passphrase"; npm run encrypt')
  process.exit(1)
}
if (!fs.existsSync(DATA_DIR)) {
  console.error(`[encrypt] ${DATA_DIR} not found — run "npm run data" first.`)
  process.exit(1)
}

const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.json'))
if (!files.length) {
  console.error('[encrypt] No JSON files to encrypt.')
  process.exit(1)
}

const bundle = {}
for (const f of files) {
  bundle[f] = JSON.parse(fs.readFileSync(path.join(DATA_DIR, f), 'utf8'))
}

const plaintext = Buffer.from(JSON.stringify(bundle), 'utf8')
const keyBuf = crypto.createHash('sha256').update(KEY).digest()
const iv = crypto.randomBytes(12)
const cipher = crypto.createCipheriv('aes-256-gcm', keyBuf, iv)
const ct = Buffer.concat([cipher.update(plaintext), cipher.final()])
const tag = cipher.getAuthTag()
const blob = Buffer.concat([iv, tag, ct]).toString('base64')

const contents =
  '// AUTO-GENERATED by scripts/encrypt-data.mjs — AES-256-GCM ciphertext.\n' +
  '// Safe to commit: it is unreadable without the DATA_KEY secret.\n' +
  '// Regenerate with:  DATA_KEY=... npm run encrypt\n' +
  `export const BLOB = '${blob}'\n`

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, contents)
console.log(`[encrypt] wrote ${path.relative(ROOT, OUT)}`)
console.log(`[encrypt] ${files.length} files, ${plaintext.length} bytes -> ${blob.length} bytes ciphertext`)
